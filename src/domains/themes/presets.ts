export function findPreset(id: string | null | undefined): ThemePreset | undefined {
  return id ? THEME_PRESETS.find((p) => p.id === id) : undefined;
}

/** A theme with a preset's values copied in. What a preset doesn't set
 * (a heading font, a gradient) is cleared, so nothing from the last look
 * lingers; the logo, background image, progress and custom CSS stay. */
export function applyPreset(theme: ThemeV1, preset: ThemePreset): ThemeV1 {
  return {
    ...theme,
    textColor: undefined,
    libraryFont: undefined,
    customFont: undefined,
    headingFont: undefined,
    headingWeight: undefined,
    backgroundGradient: undefined,
    cornerRadius: undefined,
    spacing: undefined,
    ...preset.theme,
    preset: preset.id,
  };
}
