-- Fonts and themes to the developer spec (26 Nov 2026, item 3).
--
-- * font_families: the font library's catalogue (1,700+ open-licensed
--   Google Fonts families with their category, weights, scripts and
--   popularity). Seeded here from font-data.ts; the daily retention job
--   refreshes it from Google's public metadata once a month. Anyone may
--   read it (it's a public catalogue).
-- * brand_themes: a workspace's own saved themes, offered first in the
--   builder. Members read them; owners, admins and editors change them.

create table public.font_families (
  family text primary key check (family ~ '^[A-Za-z0-9 ]{2,60}$'),
  category text not null check (category in ('sans', 'serif', 'display', 'handwriting', 'mono')),
  weights integer[] not null check (weights <@ array[400, 600, 700] and cardinality(weights) > 0),
  scripts text[] not null default '{}',
  popularity integer not null default 99999,
  refreshed_at timestamptz not null default now()
);
alter table public.font_families enable row level security;
create policy "font_families: anyone can read" on public.font_families
  for select to anon, authenticated using (true);
revoke all on public.font_families from anon, authenticated;
grant select on public.font_families to anon, authenticated;
grant all on public.font_families to service_role;

