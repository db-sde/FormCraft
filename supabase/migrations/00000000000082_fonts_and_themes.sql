-- At most 50 per workspace.
create function private.limit_brand_themes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.brand_themes where workspace_id = new.workspace_id) >= 50 then
    raise exception 'a workspace can keep up to 50 brand themes' using errcode = 'P0001';
  end if;
  return new;
end;
$$;
create trigger brand_themes_limit before insert on public.brand_themes
  for each row execute function private.limit_brand_themes();
