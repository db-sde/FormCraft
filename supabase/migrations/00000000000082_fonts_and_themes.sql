/** Replaces the catalogue with a fresh import (the monthly refresh):
 * refused unless it has at least 1,700 families, so a bad download can't
 * empty the library. Families that left Google's catalogue are removed. */
create function public.ops_replace_font_families(p_fonts jsonb)
returns integer
language plpgsql
security definer
set search_path = ''
set statement_timeout = '30s'
as $$
declare
  v_n integer;
begin
  if jsonb_typeof(p_fonts) <> 'array' or jsonb_array_length(p_fonts) < 1700 then
    raise exception 'expected at least 1,700 font families';
  end if;
  insert into public.font_families (family, category, weights, scripts, popularity, refreshed_at)
  select f->>'family', f->>'category',
         array(select jsonb_array_elements_text(f->'weights'))::integer[],
         array(select jsonb_array_elements_text(f->'scripts')),
         (f->>'popularity')::integer, now()
    from jsonb_array_elements(p_fonts) f
   where (f->>'family') ~ '^[A-Za-z0-9 ]{2,60}$'
  on conflict (family) do update set
    category = excluded.category,
    weights = excluded.weights,
    scripts = excluded.scripts,
    popularity = excluded.popularity,
    refreshed_at = excluded.refreshed_at;
  get diagnostics v_n = row_count;
  delete from public.font_families where refreshed_at < now() - interval '1 minute';
  return v_n;
end;
$$;
revoke all on function public.ops_replace_font_families(jsonb) from public, anon, authenticated;
grant execute on function public.ops_replace_font_families(jsonb) to service_role;

