/**
 * Regenerates src/domains/themes/font-data.ts from Google Fonts' public
 * metadata (developer spec item 3). Fails if fewer than 1,700 families
 * come back, since the pricing page promises 1,700+.
 *
 *   npx tsx scripts/fonts-sync.ts
 */
import { writeFileSync } from "node:fs";
import {
  encodeFont,
  parseGoogleFontsMetadata,
} from "../src/domains/themes/font-metadata";

async function main() {
  const res = await fetch("https://fonts.google.com/metadata/fonts");
  if (!res.ok) throw new Error(`Google Fonts metadata: HTTP ${res.status}`);
  const fonts = parseGoogleFontsMetadata(await res.text());
  if (fonts.length < 1700)
    throw new Error(`Only ${fonts.length} families; expected 1,700+`);
  const day = new Date().toISOString().slice(0, 10);
  writeFileSync(
    "src/domains/themes/font-data.ts",
    `/**
   * The font library's families (generated by scripts/fonts-sync.ts on ${day}
   * from Google Fonts' public metadata; ${fonts.length.toLocaleString()} families, most
   * popular first). "Family|category|weights|scripts": see font-metadata.ts.
   * The database's font_families table is refreshed monthly from the same
   * source; this file is its seed and the fallback when it's unreachable.
   */
  export const FONT_LIBRARY: readonly string[] = [
  ${fonts.map((f) => `  ${JSON.stringify(encodeFont(f))},`).join("\n")}
  ];
  `,
  );
  console.log(`Wrote ${fonts.length} families.`);
}

void main();
